import os
from typing import Dict, Any, List, Optional

STATUTORY_DISCLAIMER = (
    "\n\n============================================================\n"
    "[STATUTORY SAFETY DISCLAIMER]\n"
    "This output is generated by an AI-assisted decision-support system.\n"
    "It does NOT constitute an engineering safety certification, nor does it\n"
    "authorize mine entry or replace the statutory assessment of a certified\n"
    "Mine Manager, Overman, or Competent Person under CMR 2017 / MMR 1961.\n"
    "============================================================"
)

SYSTEM_SAFETY_PROMPT = """You are BHOOmiKAVACH AI, an authoritative, certified Mining Geotechnical & Safety AI Advisor specializing in Directorate General of Mines Safety (DGMS) Accident Code 0111 ("Fall of Roof", Ground Movement 0100) across Indian underground coal and non-coal mines.

YOUR MISSION:
Deliver decisive, role-tailored, technically precise, and regulation-backed safety guidance to save lives and prevent fatal roof falls.

CORE PRINCIPLES & SAFETY POLICY:
1. LIFE SAFETY FIRST: In any scenario with drummy/heavy roof, excessive convergence (>1.5 mm/hr), or unsupported spans, command IMMEDIATE WITHDRAWAL of all personnel to supported roadways.
2. STATUTORY RIGOR: Always cite relevant sections from Coal Mines Regulations 2017 (e.g., Reg 111 Gallery Dimensions, Reg 112 Working of Coal Seams, Reg 123 Support Plan, Reg 125 Systematic Support Rules, Reg 129 Examination of Working Places) or Metalliferous Mines Regulations 1961 (Reg 106, 108, 110), and DGMS Technical Circulars (e.g. Circular 03/2010 Strata Management, Circular 06/2013 Roof Bolting).
3. NON-CAUSAL MACHINE LEARNING LANGUAGE: When referencing ML model scores or SHAP factors, strictly state that a parameter "contributed to the elevated model risk assessment", NEVER state that a feature "caused the fall".
4. ROLE-TAILORED CLARITY: Format action steps specifically for the designated role (Worker, Supervisor, Safety Officer, Mining Engineer, Geotechnical Engineer, Mine Manager, Executive).
5. EVIDENCE GROUNDING: Strictly ground your analysis in the provided real DGMS historical accident cases, RAG regulatory excerpts, and live geomechanical sensor metrics. Do not fabricate mine names, accident years, or regulation numbers.
"""


def get_gemini_client(api_key: Optional[str] = None):
    """
    Returns an initialized Gemini client if an API key is available.
    Supports google.genai or falls back to google.generativeai.
    """
    key = api_key or os.getenv("GEMINI_API_KEY")
    if not key:
        return None, None

    # Try modern google.genai SDK
    try:
        from google import genai
        client = genai.Client(api_key=key)
        return "google.genai", client
    except Exception:
        pass

    # Try google.generativeai SDK
    try:
        import google.generativeai as gai
        gai.configure(api_key=key)
        return "google.generativeai", gai
    except Exception:
        pass

    return None, None


def is_gemini_available(api_key: Optional[str] = None) -> bool:
    sdk_type, client = get_gemini_client(api_key)
    return client is not None


def generate_gemini_safety_advisory(
    query: str,
    user_role: str = "Supervisor",
    mine_context: Optional[Dict[str, Any]] = None,
    risk_data: Optional[Dict[str, Any]] = None,
    shap_data: Optional[Dict[str, Any]] = None,
    rules_triggered: Optional[Dict[str, Any]] = None,
    similar_accidents: Optional[List[Dict[str, Any]]] = None,
    rag_evidence: Optional[List[Dict[str, Any]]] = None,
    api_key: Optional[str] = None
) -> Optional[str]:
    """
    Generates a natural, deeply informed safety decision-support narrative using Google Gemini.
    """
    sdk_type, client = get_gemini_client(api_key)
    if not client:
        return None

    model_name = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")

    # Build contextual background prompt
    context_blocks = []

    context_blocks.append(f"TARGET USER ROLE: {user_role}")
    context_blocks.append(f"USER QUERY: {query}\n")

    if mine_context:
        context_blocks.append("--- LIVE MINE OBSERVATION METRICS ---")
        for k, v in list(mine_context.items())[:12]:
            context_blocks.append(f"  * {k}: {v}")
        context_blocks.append("")

    if risk_data:
        context_blocks.append("--- MACHINE LEARNING ENSEMBLE RISK ASSESSMENT ---")
        context_blocks.append(f"  * Assessed Risk Tier: {risk_data.get('assessed_risk', 'UNKNOWN')}")
        context_blocks.append(f"  * Prediction Confidence: {risk_data.get('confidence', 'UNKNOWN')}")
        context_blocks.append(f"  * Probabilities: {risk_data.get('probabilities', {})}")
        context_blocks.append("")

    if shap_data and "top_contributors" in shap_data:
        context_blocks.append("--- SHAP FEATURE ATTRIBUTION (Top Influencing Parameters) ---")
        for c in shap_data["top_contributors"][:5]:
            context_blocks.append(f"  * {c.get('feature')}: {c.get('impact_direction')} (importance: {c.get('importance', 0):.4f})")
        context_blocks.append("")

    if rules_triggered and rules_triggered.get("triggered_rules"):
        context_blocks.append("--- STATUTORY SAFETY RULES TRIGGERED ---")
        for r in rules_triggered["triggered_rules"]:
            context_blocks.append(f"  * [{r.get('severity')}] {r.get('title')} ({r.get('regulation')}): {r.get('finding')}")
        context_blocks.append("")

    if similar_accidents:
        context_blocks.append("--- RELEVANT DGMS FATAL ACCIDENT PRECEDENTS (FAISS Cosine Retrieval) ---")
        for m in similar_accidents[:3]:
            if "error" not in m:
                context_blocks.append(
                    f"  * {m.get('mine')} ({m.get('year')}, {m.get('state')}) | Fatalities: {m.get('fatalities')} | "
                    f"Root Cause: {m.get('root_cause')} | Regulations: {m.get('regulations')}\n"
                    f"    Summary: {str(m.get('description', ''))[:180]}..."
                )
        context_blocks.append("")

    if rag_evidence:
        context_blocks.append("--- STATUTORY REGULATIONS & DGMS TECHNICAL CIRCULARS (FAISS RAG) ---")
        for ev in rag_evidence[:3]:
            if "error" not in ev:
                context_blocks.append(
                    f"  * [{ev.get('category')}] {ev.get('title')} ({ev.get('source')}, {ev.get('page')}):\n"
                    f"    {str(ev.get('content', ''))[:220]}..."
                )
        context_blocks.append("")

    context_blocks.append(
        "INSTRUCTIONS FOR YOUR RESPONSE:\n"
        "1. Start with an executive summary addressing the user's specific query.\n"
        "2. Break down the geomechanical situation and why the risk level is assigned.\n"
        "3. Provide 3 prioritized, role-tailored action items (Immediate Life Safety, Engineering Support Control, and Strata Monitoring).\n"
        "4. Explicitly cite the matching DGMS precedents and Coal Mines Regulations / Circulars from the context above.\n"
        "5. Maintain a professional, decisive tone suitable for an underground mine safety officer."
    )

    full_prompt = "\n".join(context_blocks)

    try:
        if sdk_type == "google.genai":
            response = client.models.generate_content(
                model=model_name,
                contents=full_prompt,
                config={
                    "system_instruction": SYSTEM_SAFETY_PROMPT,
                    "temperature": 0.2,
                }
            )
            narrative = response.text
        elif sdk_type == "google.generativeai":
            model = client.GenerativeModel(
                model_name=model_name,
                system_instruction=SYSTEM_SAFETY_PROMPT
            )
            response = model.generate_content(
                full_prompt,
                generation_config={"temperature": 0.2}
            )
            narrative = response.text
        else:
            return None

        if narrative:
            return narrative.strip() + STATUTORY_DISCLAIMER
        return None

    except Exception as e:
        print(f"[WARN] Gemini safety advisory generation failed: {e}")
        # Try fallback model if gemini-2.5-flash failed
        if model_name != "gemini-1.5-flash":
            try:
                if sdk_type == "google.genai":
                    fallback_resp = client.models.generate_content(
                        model="gemini-1.5-flash",
                        contents=full_prompt,
                        config={"system_instruction": SYSTEM_SAFETY_PROMPT, "temperature": 0.2}
                    )
                    return fallback_resp.text.strip() + STATUTORY_DISCLAIMER
            except Exception:
                pass
        return None
